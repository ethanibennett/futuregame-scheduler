#!/usr/bin/env node
'use strict';
/*
 * Regenerate data/venue-directory.json — the venue coordinates the server falls back on when a
 * feed row carries none of its own (see lib/venue-coords.js and resolveVenueCoords in server.js).
 *
 * READ-ONLY over the MTT watcher's database. It reads two things the watcher already stores and
 * never parses:
 *
 *   1. PokerAtlas /api/venues payloads (raw_response, venue_id='venue-directory'). Every venue
 *      there carries `latitude` / `longitude` — real coordinates, not a geocode — but the
 *      watcher's venue_directory table keeps only id/name/url/city_state. All stored payloads
 *      are unioned, newest first, because the endpoint 500s on most limits and a partial page
 *      covers a different subset each time.
 *   2. WSOP.com circuit-stop pages (source 'wsop-circuit'). Their Nuxt payload names the room
 *      (venueTitle), its town (venueLocation) and an ISO country (countryId). The watcher emits
 *      these stops with property = null, so this is the only place the room is named.
 *
 * Usage (on the Windows box, where the watcher lives):
 *   node scripts/build-venue-directory.js [path/to/mtt-series.db]
 * WATCHER_DIR overrides where better-sqlite3 is loaded from (the watcher's own node_modules —
 * this repo does not depend on it).
 *
 * This is a BOOTSTRAP. The durable path is the watcher emitting venue_lat / venue_lng /
 * venue_location per row (docs/venue-coords.md); once it does, a stale snapshot only matters
 * for rooms the watcher cannot place.
 */
const path = require('path');
const fs = require('fs');
const zlib = require('zlib');
const { createRequire } = require('module');
const { wsopSeriesName } = require('../lib/venue-coords');

const WATCHER_DIR = process.env.WATCHER_DIR || 'D:/projects/mtt-series-watcher';
const DB = process.argv[2] || path.join(WATCHER_DIR, 'data', 'mtt-series.db');
const OUT = path.join(__dirname, '..', 'data', 'venue-directory.json');

const Database = createRequire(path.join(WATCHER_DIR, 'package.json'))('better-sqlite3');
const db = new Database(DB, { readonly: true, fileMustExist: true });

function bodyOf(row) {
  if (row.body != null) return row.body;
  const blob = db.prepare('SELECT body_gz FROM raw_blob WHERE hash = ?').get(row.body_hash);
  return blob ? zlib.gunzipSync(blob.body_gz).toString('utf8') : null;
}

// ── 1. PokerAtlas directory ──
const paRows = db.prepare(
  `SELECT body_hash, MAX(ts) AS ts, NULL AS body FROM raw_response
    WHERE source = 'pokeratlas-schedule' AND venue_id = 'venue-directory' AND status = 200
    GROUP BY body_hash ORDER BY ts DESC`
).all();
const pa = new Map();
for (const r of paRows) {
  const body = bodyOf(r);
  if (!body) continue;
  let venues;
  try { venues = JSON.parse(body).venues; } catch { continue; }
  if (!Array.isArray(venues)) continue;
  for (const v of venues) {
    if (v.id == null || pa.has(String(v.id))) continue; // newest payload wins
    const lat = Number(v.latitude), lng = Number(v.longitude);
    if (!Number.isFinite(lat) || !Number.isFinite(lng) || (lat === 0 && lng === 0)) continue;
    pa.set(String(v.id), [Number(v.id), String(v.name || '').trim(), String(v.city_state || '').trim(),
      Math.round(lat * 1e5) / 1e5, Math.round(lng * 1e5) / 1e5]);
  }
}

// ── 2. WSOP.com circuit stops ──
const NUXT = /"([^"]*)","([A-Z]+)","([A-Z]{2})","([^"]*)","([^"]*)","(\d{4}-\d\d-\d\d)","(\d{4}-\d\d-\d\d)","([^"]*)"/;
const decode = (s) => s.replace(/\\u0026/g, '&').replace(/&amp;/g, '&').replace(/&#39;/g, "'").trim();
const stopRows = db.prepare(
  `SELECT r.venue_id, r.ts, r.body, r.body_hash FROM raw_response r
     JOIN (SELECT venue_id, MAX(ts) AS ts FROM raw_response
            WHERE source = 'wsop-circuit' AND status = 200 GROUP BY venue_id) m
       ON m.venue_id = r.venue_id AND m.ts = r.ts
    WHERE r.source = 'wsop-circuit'`
).all();
const stops = {};
for (const r of stopRows) {
  const html = bodyOf(r);
  if (!html) continue;
  const m = html.match(NUXT);
  const title = html.match(/<title>([\s\S]*?)<\/title>/i);
  if (!m || !title) continue;
  const [, , , country, venueTitle, venueLocation] = m;
  // The watcher names the series from the page title + the slug's year, or the year it was
  // collected when the slug has none (wsop-circuit.ts seriesNameFrom) — reproduced exactly.
  const venue = wsopSeriesName(title[1], r.venue_id, r.ts);
  stops[venue] = { slug: r.venue_id, property: decode(venueTitle), location: decode(venueLocation), country };
}
db.close();

const out = {
  _about: 'Generated by scripts/build-venue-directory.js from the MTT watcher DB (read-only). ' +
    'pokeratlas rows are [id, name, city_state, lat, lng] from PokerAtlas /api/venues; wsop_stops maps ' +
    'the feed venue string of a WSOP.com circuit stop to the room its page names. Do not hand-edit.',
  generated_at: new Date().toISOString(),
  pokeratlas: [...pa.values()].sort((a, b) => a[0] - b[0]),
  wsop_stops: Object.fromEntries(Object.entries(stops).sort(([a], [b]) => a.localeCompare(b))),
};
fs.mkdirSync(path.dirname(OUT), { recursive: true });
// One venue per line: diffable, and a third the size of pretty-printed objects.
const lines = [
  '{',
  `  "_about": ${JSON.stringify(out._about)},`,
  `  "generated_at": ${JSON.stringify(out.generated_at)},`,
  '  "pokeratlas": [',
  out.pokeratlas.map((v) => '    ' + JSON.stringify(v)).join(',\n'),
  '  ],',
  '  "wsop_stops": {',
  Object.entries(out.wsop_stops).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n'),
  '  }',
  '}',
];
fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`venue directory: ${out.pokeratlas.length} PokerAtlas venues from ${paRows.length} payload(s), ` +
  `${Object.keys(stops).length} WSOP.com stop(s) → ${path.relative(process.cwd(), OUT)}`);
