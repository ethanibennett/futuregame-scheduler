// futurega.me/live's stylesheet, generated from src/styles.css (Laws of UX pick 13, owner 2026-11-10).
// The landing page used to import the whole app stylesheet (about 450 KB, 70 KB compressed, render-
// blocking) and used a few percent of it. This keeps, from styles.css itself, so the two can never
// drift: every @font-face, the token blocks (:root and the theme and contrast variants), the base
// element rules, and the rules whose classes are all ones the landing page renders (LIVE_CLASSES).
// The page's own files (live-page.css, backer-page.css, analytics.css) are imported whole by
// LivePage.jsx. vite.config.js calls writeLiveCss() whenever Vite starts, beside writeLiveHtml().
// Output: src/live.generated.css (gitignored), imported by src/live-main.jsx.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

/* The classes LivePage.jsx renders from styles.css (its own lp- / bp- / an- rules come from its own
   files), ThemeButton's, and the grid overlay's (the guards load /live with ?gridOverlay=1). */
const LIVE_CLASSES = new Set([
  'app-shell', 'top-bar', 'top-bar-title', 'content-area', 'btn', 'btn-ghost', 'btn-icon', 'ctl', 'ctl-cap',
  'bp-shell', 'bp-top', 'bp-top-actions', 'bp-content', 'lp-shell', 'lp-content',
]);
const LIVE_CLASS_PREFIXES = ['grid-dev-', 'lp-', 'an-'];
const LIVE_ELEMENTS = new Set([
  'html', 'body', 'h1', 'h2', 'h3', 'p', 'ul', 'li', 'a', 'button', 'small', 'main', 'header', 'footer',
  'section', 'div', 'span', 'svg', 'path', 'polyline', 'circle', 'line', 'rect', 'g', 'strong', 'em',
]);
const ALLOWED_IDS = new Set(['root']);

const classOk = (c) => LIVE_CLASSES.has(c) || LIVE_CLASS_PREFIXES.some((p) => c.startsWith(p));

/** Whether one selector (no commas at the top level) can match on the landing page. */
export function selectorFits(sel) {
  let s = sel.replace(/\[[^\]]*\]/g, '[]');                         // attribute values say nothing about classes
  s = s.replace(/:not\((?:[^()]|\([^()]*\))*\)/g, '');               // a negated class is not required
  for (const m of s.matchAll(/:(?:is|where|has)\(((?:[^()]|\([^()]*\))*)\)/g)) {
    const inner = m[1].split(',').map((x) => x.trim()).filter(Boolean);
    if (!inner.some((x) => selectorFits(x))) return false;          // any one alternative is enough
  }
  s = s.replace(/:(?:is|where|has)\((?:[^()]|\([^()]*\))*\)/g, '');
  s = s.replace(/::?[a-zA-Z-]+(\([^()]*\))?/g, '');                  // other pseudo-classes and elements
  for (const m of s.matchAll(/\.([A-Za-z0-9_-]+)/g)) if (!classOk(m[1])) return false;
  for (const m of s.matchAll(/#([A-Za-z0-9_-]+)/g)) if (!ALLOWED_IDS.has(m[1])) return false;
  const bare = s.replace(/\.[A-Za-z0-9_-]+|#[A-Za-z0-9_-]+|\[\]/g, ' ');
  for (const m of bare.matchAll(/(?:^|[\s>+~])([a-zA-Z][a-zA-Z0-9-]*)/g)) {
    if (!LIVE_ELEMENTS.has(m[1].toLowerCase())) return false;
  }
  return true;
}

export function liveCss(source) {
  const root = postcss.parse(source);
  const keepFrames = new Set();
  root.walkAtRules((at) => {
    if (at.name === 'font-face' || at.name === 'keyframes' || at.name === '-webkit-keyframes') return;
    if (at.name === 'import' || at.name === 'charset') return;
  });
  root.walkRules((rule) => {
    const parent = rule.parent;
    if (parent && parent.type === 'atrule' && /keyframes$/.test(parent.name)) return;   // a keyframe step
    const kept = rule.selectors.filter((sel) => selectorFits(sel));
    if (!kept.length) { rule.remove(); return; }
    rule.selectors = kept;
    rule.walkDecls(/^(animation|animation-name)$/, (d) => {
      for (const w of d.value.split(/[\s,]+/)) keepFrames.add(w);
    });
  });
  // Keyframes nothing kept refers to, and the blocks left empty.
  root.walkAtRules(/keyframes$/, (at) => { if (!keepFrames.has(at.params.trim())) at.remove(); });
  let removed = true;
  while (removed) {
    removed = false;
    root.walkAtRules((at) => {
      if (at.name === 'font-face') return;
      if (at.nodes && !at.nodes.some((n) => n.type !== 'comment')) { at.remove(); removed = true; }
    });
  }
  root.walkComments((c) => c.remove());
  return '/* Generated by vite-app/scripts/make-live-css.mjs from src/styles.css. Do not edit. */\n' + root.toString();
}

export function writeLiveCss() {
  const src = fs.readFileSync(path.join(dir, 'src', 'styles.css'), 'utf8');
  const out = liveCss(src);
  fs.writeFileSync(path.join(dir, 'src', 'live.generated.css'), out);
  return out.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const n = writeLiveCss();
  console.log(`src/live.generated.css written: ${n} bytes`);
}
