// The card faces, inside the app's code (owner, 2026-11-15: "4d not rendering, this is really bad"; see
// src/utils/card-faces.js). Generated from public/cards/cards_gui_*.svg whenever Vite starts (vite.config.js), so the
// files stay the one source. Every face embeds the same font (Univers Condensed, base64, 2.9 KB of a 4 KB face), so
// the font is written once and each face carries a marker where it goes: about 80 KB of source rather than 240 KB.
// Output: src/card-faces.generated.js (gitignored).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FONT_MARK = '@@CARD_FONT@@';

export function writeCardFaces() {
  const cards = path.join(dir, 'public', 'cards');
  const files = fs.readdirSync(cards).filter((f) => /^cards_gui_\w+\.svg$/.test(f)).sort();
  let font = null;
  const faces = {};
  for (const f of files) {
    const svg = fs.readFileSync(path.join(cards, f), 'utf8');
    const m = /base64,([A-Za-z0-9+/=]+)/.exec(svg);
    const key = /^cards_gui_(\w+)\.svg$/.exec(f)[1];
    if (m && (font === null || m[1] === font)) {
      font = m[1];
      faces[key] = svg.replace(m[1], FONT_MARK);
    } else {
      faces[key] = svg;                       // a face with no font, or another one, is kept whole
    }
  }
  if (files.length !== 52) console.warn(`[card-faces] ${files.length} faces in public/cards, expected 52`);
  const out = '// Generated by vite-app/scripts/make-card-faces.mjs from public/cards whenever Vite starts. Do not edit.\n'
    + `export const FONT_MARK = ${JSON.stringify(FONT_MARK)};\n`
    + `export const FONT = ${JSON.stringify(font || '')};\n`
    + `export const FACES = ${JSON.stringify(faces)};\n`;
  const target = path.join(dir, 'src', 'card-faces.generated.js');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) fs.writeFileSync(target, out);
}
